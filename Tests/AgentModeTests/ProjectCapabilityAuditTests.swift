    func testRecordSyncMergesTargetsFromSeparateEngines() throws {
        let codexTarget = project.rootURL.appendingPathComponent(".codex/config.toml", isDirectory: false)
        let claudeTarget = project.rootURL.appendingPathComponent(".mcp.json", isDirectory: false)
        try FileManager.default.createDirectory(at: codexTarget.deletingLastPathComponent(), withIntermediateDirectories: true)
        try "# Generated by OpenPetAgent Codex projection. Do not edit by hand.\n\nmodel = \"x\"\n".write(to: codexTarget, atomically: true, encoding: .utf8)
        try "{}".write(to: claudeTarget, atomically: true, encoding: .utf8)
        let codexPlan = ProjectionPlan(
            projectID: project.id,
            engineID: AgentEngineKind.codex.rawValue,
            pluginID: "codex",
            operations: [.writeFile(contents: "model = \"x\"", destination: codexTarget)]
        )
        let claudePlan = ProjectionPlan(
            projectID: project.id,
            engineID: AgentEngineKind.claudeCode.rawValue,
            pluginID: "claude-code",
            operations: [.writeFile(contents: "{}", destination: claudeTarget)]
        )
        let store = ProjectCapabilityAuditStore()

        try store.recordSync(project: project, plans: [codexPlan], date: Date(timeIntervalSince1970: 1))
        try store.recordSync(project: project, plans: [claudePlan], date: Date(timeIntervalSince1970: 2))

        let paths = try store.load(project: project).generatedTargets.map(\.path).sorted()
        XCTAssertEqual(paths, [claudeTarget.path, codexTarget.path].sorted())
    }

    func testRecordBackupStoresExistingGeneratedTargetBeforeSync() throws {
        let target = project.rootURL.appendingPathComponent(".codex/config.toml", isDirectory: false)
        try FileManager.default.createDirectory(at: target.deletingLastPathComponent(), withIntermediateDirectories: true)
        try "# Generated by OpenPetAgent Codex projection. Do not edit by hand.\n\nmodel = \"old\"\n".write(to: target, atomically: true, encoding: .utf8)
        let plan = ProjectionPlan(
            projectID: project.id,
            engineID: AgentEngineKind.codex.rawValue,
            pluginID: "codex",
            operations: [.writeFile(contents: "model = \"new\"", destination: target)]
        )
        let store = ProjectCapabilityAuditStore()

        try store.recordBackup(project: project, plans: [plan], date: Date(timeIntervalSince1970: 3))

        let state = try store.load(project: project)
        let backup = try XCTUnwrap(state.backups.first)
        XCTAssertEqual(backup.engineID, AgentEngineKind.codex.rawValue)
        XCTAssertEqual(backup.pluginID, "codex")
        XCTAssertEqual(backup.targetPath, target.path)
        XCTAssertTrue(FileManager.default.fileExists(atPath: backup.backupPath))
        XCTAssertEqual(
            try String(contentsOf: URL(fileURLWithPath: backup.backupPath), encoding: .utf8),
            "# Generated by OpenPetAgent Codex projection. Do not edit by hand.\n\nmodel = \"old\"\n"
        )
    }

