    func testSourceConfirmationAllowsMatchingSourceOnlyAndCanBeRevoked() throws {
        let store = auditStore()
        let source = ProjectPluginSourceMetadata(
            kind: .git,
            url: "https://example.com/plugin.git",
            revision: "abc123"
        )
        let changed = ProjectPluginSourceMetadata(
            kind: .git,
            url: "https://example.com/plugin.git",
            revision: "def456"
        )
        let pluginRoot = ProjectConfig.pluginDirectory(for: project, pluginID: "remote")
        try FileManager.default.createDirectory(at: pluginRoot, withIntermediateDirectories: true)
        try Data(#"{ "schemaVersion": 1, "id": "remote", "name": "Remote", "source": { "kind": "git", "url": "https://example.com/plugin.git", "revision": "abc123" }, "enabled": true, "capabilities": [] }"#.utf8)
            .write(to: pluginRoot.appendingPathComponent("plugin.json"), options: .atomic)

        try store.confirmSource(project: project, pluginID: "remote", source: source, date: Date(timeIntervalSince1970: 6))

        XCTAssertTrue(try store.isSourceConfirmed(project: project, pluginID: "remote", source: source))
        XCTAssertFalse(try store.isSourceConfirmed(project: project, pluginID: "remote", source: changed))
        let confirmation = try XCTUnwrap(store.loadSourceConfirmations(project: project).confirmations.first)
        XCTAssertEqual(confirmation.confirmedAtDescription, "1970-01-01T00:00:06Z")
        XCTAssertFalse(FileManager.default.fileExists(atPath: ProjectConfig.capabilityAuditStateURL(for: project).path))
        XCTAssertTrue(FileManager.default.fileExists(atPath: root.appendingPathComponent("source-confirmations/p.json").path))

        try store.revokeSourceConfirmation(project: project, pluginID: "remote")

        XCTAssertFalse(try store.isSourceConfirmed(project: project, pluginID: "remote", source: source))
        XCTAssertTrue(try store.loadSourceConfirmations(project: project).confirmations.isEmpty)
    }

