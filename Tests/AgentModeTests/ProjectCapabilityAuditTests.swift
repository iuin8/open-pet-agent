        try FileManager.default.createDirectory(at: pluginRoot.appendingPathComponent("mcp", isDirectory: true), withIntermediateDirectories: true)
        try Data(#"{ "schemaVersion": 1, "id": "remote", "name": "Remote", "source": { "kind": "git", "url": "https://example.com/plugin.git", "revision": "abc123" }, "enabled": true, "capabilities": ["mcp"], "mcp": ["mcp/.servers.json#filesystem"] }"#.utf8)
            .write(to: pluginRoot.appendingPathComponent("plugin.json"), options: .atomic)
        let hiddenMCP = pluginRoot.appendingPathComponent("mcp/.servers.json")
        try Data(#"{ "mcpServers": { "filesystem": { "type": "local", "command": ["npx"] } } }"#.utf8)
            .write(to: hiddenMCP, options: .atomic)

        try store.confirmSource(project: project, pluginID: "remote", source: source, date: Date(timeIntervalSince1970: 6))
        try Data(#"{ "mcpServers": { "filesystem": { "type": "local", "command": ["evil"] } } }"#.utf8)
            .write(to: hiddenMCP, options: .atomic)

        XCTAssertFalse(try store.isSourceConfirmed(project: project, pluginID: "remote", source: source))
    }

    private func auditStore() -> ProjectCapabilityAuditStore {
        ProjectCapabilityAuditStore { [self] project in
            self.root.appendingPathComponent("source-confirmations", isDirectory: true)
                .appendingPathComponent("\(project.id).json", isDirectory: false)
        }
    }

    /// 播种 ownership 登记(manifest-only:目标先登记才视为 PetAgent 生成)。
    private func own(_ relativePath: String, kind: ProjectionGeneratedTarget.Kind) throws {
        var manifest = (try? ProjectionGeneratedManifestStore.load(projectRoot: project.rootURL)) ?? ProjectionGeneratedManifest()
        manifest.claim(path: relativePath, kind: kind, engineID: AgentEngineKind.codex.rawValue)
        try ProjectionGeneratedManifestStore.save(manifest, projectRoot: project.rootURL)
    }

    /// 撤销 ownership 登记(模拟目标失去生成归属)。
    private func disown(_ relativePath: String) throws {
        var manifest = (try? ProjectionGeneratedManifestStore.load(projectRoot: project.rootURL)) ?? ProjectionGeneratedManifest()
        manifest.release(path: relativePath)
        try ProjectionGeneratedManifestStore.save(manifest, projectRoot: project.rootURL)
    }
