    func testRestoreLatestBackupRestoresAllTargetsFromLatestSync() throws {
        let config = project.rootURL.appendingPathComponent(".codex/config.toml", isDirectory: false)
        let skill = project.rootURL.appendingPathComponent(".agents/skills/review", isDirectory: true)
        try FileManager.default.createDirectory(at: config.deletingLastPathComponent(), withIntermediateDirectories: true)
        try FileManager.default.createDirectory(at: skill, withIntermediateDirectories: true)
        try "# Generated by OpenPetAgent Codex projection. Do not edit by hand.\n\nmodel = \"old\"\n".write(to: config, atomically: true, encoding: .utf8)
        try "generated".write(to: skill.appendingPathComponent(".open-pet-agent-generated"), atomically: true, encoding: .utf8)
        try "old skill".write(to: skill.appendingPathComponent("SKILL.md"), atomically: true, encoding: .utf8)
        let source = project.rootURL.appendingPathComponent("source", isDirectory: true)
        let plan = ProjectionPlan(
            projectID: project.id,
            engineID: AgentEngineKind.codex.rawValue,
            pluginID: "codex",
            operations: [
                .writeFile(contents: "model = \"new\"", destination: config),
                .copyDirectory(source: source, destination: skill)
            ]
        )
        let store = ProjectCapabilityAuditStore()
        try store.recordBackup(project: project, plans: [plan], date: Date(timeIntervalSince1970: 3))
        try "# Generated by OpenPetAgent Codex projection. Do not edit by hand.\n\nmodel = \"new\"\n".write(to: config, atomically: true, encoding: .utf8)
        try FileManager.default.removeItem(at: skill.appendingPathComponent("SKILL.md"))
        try "new skill".write(to: skill.appendingPathComponent("SKILL.md"), atomically: true, encoding: .utf8)

        try store.restoreLatestBackup(project: project)

        XCTAssertEqual(
            try String(contentsOf: config, encoding: .utf8),
            "# Generated by OpenPetAgent Codex projection. Do not edit by hand.\n\nmodel = \"old\"\n"
        )
        XCTAssertEqual(try String(contentsOf: skill.appendingPathComponent("SKILL.md"), encoding: .utf8), "old skill")
    }

