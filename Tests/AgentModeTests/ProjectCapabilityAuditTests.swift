    func testRestoreLatestBackupRejectsSymlinkedParentOutsideProject() throws {
        let target = project.rootURL.appendingPathComponent(".agents/skills/review", isDirectory: true)
        try FileManager.default.createDirectory(at: target, withIntermediateDirectories: true)
        try "generated".write(to: target.appendingPathComponent(".open-pet-agent-generated"), atomically: true, encoding: .utf8)
        try "old skill".write(to: target.appendingPathComponent("SKILL.md"), atomically: true, encoding: .utf8)
        let plan = ProjectionPlan(
            projectID: project.id,
            engineID: AgentEngineKind.codex.rawValue,
            pluginID: "codex",
            operations: [.copyDirectory(source: project.rootURL.appendingPathComponent("source"), destination: target)]
        )
        let store = ProjectCapabilityAuditStore()
        try store.recordBackup(project: project, plans: [plan], date: Date(timeIntervalSince1970: 3))
        try FileManager.default.removeItem(at: target)
        try FileManager.default.removeItem(at: target.deletingLastPathComponent())
        let outside = root.appendingPathComponent("outside", isDirectory: true)
        try FileManager.default.createDirectory(at: outside, withIntermediateDirectories: true)
        try FileManager.default.createSymbolicLink(at: target.deletingLastPathComponent(), withDestinationURL: outside)

        XCTAssertThrowsError(try store.restoreLatestBackup(project: project))

        XCTAssertFalse(FileManager.default.fileExists(atPath: outside.appendingPathComponent("review/SKILL.md").path))
    }

    func testAcknowledgementPersistsLocalOnlyAndSuppressesDiagnostic() throws {
        let target = project.rootURL.appendingPathComponent(".mcp.json", isDirectory: false)
        try FileManager.default.createDirectory(at: target.deletingLastPathComponent(), withIntermediateDirectories: true)
        try "{\"mcpServers\":{}}".write(to: target, atomically: true, encoding: .utf8)
        let plan = ProjectionPlan(
            projectID: project.id,
            engineID: AgentEngineKind.claudeCode.rawValue,
            pluginID: "claude-code",
            operations: [.writeFile(contents: "{}", destination: target)]
        )
        let store = ProjectCapabilityAuditStore()
        let auditor = ProjectCapabilityAuditor(store: store)
        let diagnostic = try XCTUnwrap(auditor.diagnostics(project: project, plans: [plan]).first)

        try store.acknowledge(diagnostic, project: project)

        XCTAssertTrue(try store.load(project: project).acknowledgedDiagnostics.contains(ProjectCapabilityAuditStore.key(for: diagnostic)))
        XCTAssertTrue(try auditor.diagnostics(project: project, plans: [plan]).isEmpty)
        XCTAssertTrue(FileManager.default.fileExists(atPath: ProjectConfig.capabilityAuditStateURL(for: project).path))
        XCTAssertFalse(FileManager.default.fileExists(atPath: project.rootURL.appendingPathComponent(".mcp.json.open-pet-agent-state").path))
    }
