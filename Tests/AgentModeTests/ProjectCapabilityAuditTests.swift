import XCTest
@testable import AgentMode

final class ProjectCapabilityAuditTests: XCTestCase {
    private var root: URL!
    private var project: AgentProject!

    override func setUp() {
        super.setUp()
        root = FileManager.default.temporaryDirectory
            .appendingPathComponent("ProjectCapabilityAuditTests-\(UUID().uuidString)", isDirectory: true)
        try? FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        project = AgentProject(
            id: "p",
            name: "P",
            rootURL: root.appendingPathComponent("repo", isDirectory: true),
            isExternal: true,
            createdAt: Date(timeIntervalSince1970: 0)
        )
    }

    override func tearDown() {
        if let root { try? FileManager.default.removeItem(at: root) }
        super.tearDown()
    }

    func testMissingStateFileLoadsEmptyAndUsesLocalOnlyPath() throws {
        let store = ProjectCapabilityAuditStore()

        let state = try store.load(project: project)

        XCTAssertEqual(state, CapabilityAuditState())
        XCTAssertEqual(
            ProjectConfig.capabilityAuditStateURL(for: project).path,
            project.rootURL.appendingPathComponent(".open-pet-agent/state/capabilities.local.json").path
        )
        XCTAssertFalse(FileManager.default.fileExists(atPath: project.rootURL.appendingPathComponent(".mcp.json").path))
        XCTAssertFalse(FileManager.default.fileExists(atPath: project.rootURL.appendingPathComponent(".codex/config.toml").path))
    }

    func testRecordedGeneratedTargetReportsNoDriftWhenHashMatches() throws {
        let target = project.rootURL.appendingPathComponent(".codex/config.toml", isDirectory: false)
        try FileManager.default.createDirectory(at: target.deletingLastPathComponent(), withIntermediateDirectories: true)
        try "# Generated by OpenPetAgent Codex projection. Do not edit by hand.\n\nmodel = \"x\"\n".write(to: target, atomically: true, encoding: .utf8)
        let plan = ProjectionPlan(
            projectID: project.id,
            engineID: AgentEngineKind.codex.rawValue,
            pluginID: "codex",
            operations: [.writeFile(contents: "model = \"x\"", destination: target)]
        )
        let store = ProjectCapabilityAuditStore()
        try store.recordSync(project: project, plans: [plan], date: Date(timeIntervalSince1970: 1))

        let diagnostics = try ProjectCapabilityAuditor(store: store).diagnostics(project: project, plans: [plan])

        XCTAssertFalse(diagnostics.contains { $0.message.contains("drift") || $0.message.contains("漂移") })
        XCTAssertEqual(try store.load(project: project).lastSyncDescription, "1970-01-01T00:00:01Z")
    }

